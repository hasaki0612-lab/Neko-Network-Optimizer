# shellcheck shell=bash
# DNS changes through each manager, verification, auto rollback and restore.

dns_static_root() { # regular resolv.conf, no resolver daemon
  rm -f "$R/etc/resolv.conf" "$M/active/systemd-resolved"
  printf 'nameserver 10.0.0.2\nsearch example.internal\noptions edns0\n' >"$R/etc/resolv.conf"
}

section "DNS：静态 resolv.conf"
(
  t_setup
  dns_static_root
  orig=$(cat "$R/etc/resolv.conf")
  # 4 -> 2 -> Cloudflare -> IPv6? n -> confirm y -> keep y -> 0 -> 0
  out=$(neko_run '4\n2\n1\nn\ny\ny\n0\n0\n')
  assert_contains "$out" "静态文件（无管理程序）" "识别静态 resolv.conf"
  assert_contains "$out" "DNS 解析验证通过" "修改后验证解析"
  assert_contains "$out" "已确认保留本次修改" "用户确认保留"
  rc=$(cat "$R/etc/resolv.conf")
  assert_contains "$rc" "# Generated by Neko" "写入 Neko 标记"
  assert_contains "$rc" $'nameserver 1.1.1.1\nnameserver 1.0.0.1' "写入 Cloudflare DNS"
  assert_contains "$rc" "search example.internal" "保留 search"
  assert_contains "$rc" "options edns0" "保留 options"
  assert_contains "$(cat "$T/state/history.tsv")" $'\tcommitted\tdns-set\t' "DNS 变更记录"
  out=$(neko_run '4\n6\n2\ny\n0\n0\n')
  assert_eq "$(cat "$R/etc/resolv.conf")" "$orig" "恢复到 Neko 首次修改 DNS 之前"
  t_teardown
)
(
  t_setup
  dns_static_root
  orig=$(cat "$R/etc/resolv.conf")
  touch "$M/dns_fail"
  out=$(neko_run '4\n2\n1\nn\ny\n0\n0\n')
  assert_contains "$out" "DNS 解析验证失败" "检测到解析失败"
  assert_contains "$out" "正在自动回滚" "解析失败自动回滚"
  assert_eq "$(cat "$R/etc/resolv.conf")" "$orig" "回滚后 resolv.conf 与原始一致"
  t_teardown
)
(
  t_setup
  dns_static_root
  orig=$(cat "$R/etc/resolv.conf")
  echo 'GUARD_TIMEOUT=2' >"$T/etc/neko.conf"
  out=$(neko_run '4\n2\n1\nn\ny\n')
  assert_contains "$out" "确认超时，正在自动回滚" "未确认时超时回滚"
  assert_eq "$(cat "$R/etc/resolv.conf")" "$orig" "超时回滚后恢复原配置"
  t_teardown
)
(
  t_setup
  dns_static_root
  out=$(neko_run '4\n2\n4\n9.9.9.9 2620:fe::fe\n\ny\nn\n0\n0\n')
  assert_contains "$out" "未确认保留，正在回滚" "用户拒绝保留时回滚"
  out=$(neko_run '4\n2\n4\n1.1.1.1;reboot\n0\n0\n')
  assert_contains "$out" "无效的 IP 地址：1.1.1.1;reboot" "拒绝非法自定义 DNS"
  t_teardown
)

section "DNS：systemd-resolved 与 DoT"
(
  t_setup
  # 4 -> 3 (DoT) -> Cloudflare -> IPv6 y -> strict -> confirm y -> keep y
  out=$(neko_run '4\n3\n1\ny\n1\ny\ny\n0\n0\n')
  drop=$(cat "$R/etc/systemd/resolved.conf.d/99-neko-dns.conf" 2>/dev/null)
  assert_contains "$drop" "DNS=1.1.1.1#cloudflare-dns.com 1.0.0.1#cloudflare-dns.com 2606:4700:4700::1111#cloudflare-dns.com" "resolved drop-in 写入 DoT 服务器"
  assert_contains "$drop" "DNSOverTLS=yes" "严格 DoT"
  assert_contains "$(cat "$M/calls")" "systemctl restart systemd-resolved" "重启 systemd-resolved"
  assert_eq "$(readlink "$R/etc/resolv.conf")" "../run/systemd/resolve/stub-resolv.conf" "未改动 resolv.conf 符号链接"
  out=$(neko_run '0\n')
  assert_contains "$out" "DoT：已启用（严格模式）" "主菜单显示 DoT 状态"
  : >"$M/calls"
  out=$(neko_run '4\n6\n1\ny\ny\n0\n0\n')
  assert_no_file "$R/etc/systemd/resolved.conf.d/99-neko-dns.conf" "恢复：删除 Neko 的 drop-in"
  assert_contains "$(cat "$M/calls")" "systemctl restart systemd-resolved" "恢复后重启 systemd-resolved"
  t_teardown
)
(
  t_setup
  dns_static_root
  out=$(neko_run '4\n3\n0\n0\n')
  assert_contains "$out" "DoT 需要 systemd-resolved" "非 resolved 环境拒绝 DoT"
  t_teardown
)

section "DNS：dhclient / resolvconf / NetworkManager / 未知"
(
  t_setup
  dns_static_root
  echo "777 /sbin/dhclient -4 -v eth0" >"$M/ps.txt"
  mkdir -p "$R/etc/dhcp"
  printf 'option rfc3442-classless-static-routes code 121 = array of unsigned integer 8;\nrequest subnet-mask, routers;\n' >"$R/etc/dhcp/dhclient.conf"
  neko_run '4\n2\n1\nn\ny\ny\n0\n0\n' >/dev/null
  neko_run '4\n2\n2\nn\ny\ny\n0\n0\n' >/dev/null
  conf=$(cat "$R/etc/dhcp/dhclient.conf")
  assert_eq "$(grep -c 'BEGIN NEKO DNS' <<<"$conf")" 1 "重复修改不产生重复配置块"
  assert_contains "$conf" "supersede domain-name-servers 8.8.8.8, 8.8.4.4;" "dhclient supersede 规则"
  assert_contains "$conf" "request subnet-mask, routers;" "保留原有 dhclient 配置"
  assert_contains "$(cat "$R/etc/resolv.conf")" "nameserver 8.8.8.8" "同步更新 resolv.conf"
  t_teardown
)
(
  t_setup
  rm -f "$R/etc/resolv.conf" "$M/active/systemd-resolved"
  mkdir -p "$R/run/resolvconf" "$R/etc/resolvconf/resolv.conf.d"
  echo 'nameserver 10.0.0.2' >"$R/run/resolvconf/resolv.conf"
  ln -s ../run/resolvconf/resolv.conf "$R/etc/resolv.conf"
  neko_run '4\n2\n3\nn\ny\ny\n0\n0\n' >/dev/null
  assert_contains "$(cat "$R/etc/resolvconf/resolv.conf.d/head" 2>/dev/null)" $'nameserver 9.9.9.9\nnameserver 149.112.112.112' "resolvconf head 写入 Quad9"
  assert_contains "$(cat "$M/calls")" "resolvconf -u" "执行 resolvconf -u"
  assert_eq "$(readlink "$R/etc/resolv.conf")" "../run/resolvconf/resolv.conf" "未改动 resolvconf 符号链接"
  t_teardown
)
(
  t_setup
  rm -f "$R/etc/resolv.conf" "$M/active/systemd-resolved"
  printf '# Generated by NetworkManager\nnameserver 8.8.8.8\n' >"$R/etc/resolv.conf"
  touch "$M/active/NetworkManager"
  neko_run '4\n2\n1\nn\ny\ny\n0\n0\n' >/dev/null
  calls=$(cat "$M/calls")
  assert_contains "$calls" "nmcli connection modify Wired connection 1 ipv4.dns 1.1.1.1 1.0.0.1 ipv4.ignore-auto-dns yes" "nmcli 修改连接 DNS"
  assert_contains "$calls" "nmcli device reapply eth0" "nmcli reapply（不重启 NetworkManager）"
  assert_not_contains "$calls" "systemctl restart NetworkManager" "未重启 NetworkManager"
  : >"$M/calls"
  neko_run '4\n6\n1\ny\n0\n0\n' >/dev/null
  assert_contains "$(cat "$M/calls")" "nmcli connection modify Wired connection 1 ipv4.dns 8.8.8.8 ipv4.ignore-auto-dns no" "回滚恢复原连接 DNS"
  t_teardown
)
(
  t_setup
  rm -f "$R/etc/resolv.conf"
  ln -s /opt/custom/resolv.conf "$R/etc/resolv.conf"
  rm -f "$M/active/systemd-resolved"
  out=$(neko_run '4\n2\n1\nn\n0\n0\n')
  assert_contains "$out" "不支持自动修改" "未知管理方式拒绝修改"
  t_teardown
)
(
  t_setup
  export NEKO_TEST_EUID=1000
  out=$(neko_run '4\n2\n1\nn\n0\n0\n')
  assert_contains "$out" "修改 DNS需要 root 权限" "普通用户不能修改 DNS"
  t_teardown
)

