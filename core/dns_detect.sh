# shellcheck shell=bash
# Neko - detection of how the system DNS is managed.
#
# Writing /etc/resolv.conf blindly is the most common way DNS "fixes" break a
# VPS: systemd-resolved, resolvconf, NetworkManager and DHCP clients all own it
# in different ways. dns_detect decides which one is in charge.

[[ -n ${_NEKO_DNS_DETECT_LOADED:-} ]] && return 0
_NEKO_DNS_DETECT_LOADED=1

DNS_RESOLV_KIND='' DNS_RESOLV_TARGET='' DNS_MANAGER='' DNS_MANAGER_DETAIL=''
DNS_NAMESERVERS=() DNS_UPSTREAM=() DNS_SEARCH='' DNS_OPTIONS=''
DNS_RESOLVED_ACTIVE=0 DNS_NM_ACTIVE=0 DNS_DHCP_CLIENT='' DNS_NETPLAN_FILES=()
DNS_DOT='' DNS_DOH='' DNS_IMMUTABLE=0 DNS_RESOLVCONF_FLAVOR=''

dns_parse_resolv() { # dns_parse_resolv <real path> -> DNS_NAMESERVERS / DNS_SEARCH / DNS_OPTIONS
  local f=$1 k v
  DNS_NAMESERVERS=() DNS_SEARCH='' DNS_OPTIONS=''
  [[ -r $f ]] || return 1
  while read -r k v; do
    case $k in
      nameserver) DNS_NAMESERVERS+=("${v%% *}") ;;
      search | domain) DNS_SEARCH=$v ;;
      options) DNS_OPTIONS=$v ;;
    esac
  done <"$f"
}

dns_resolved_conf_value() { # last value of a [Resolve] key across resolved.conf + drop-ins
  local key=$1 f line val=''
  local files=("$(sysp /etc/systemd/resolved.conf)")
  local d
  for d in /usr/lib/systemd/resolved.conf.d /lib/systemd/resolved.conf.d /run/systemd/resolved.conf.d /etc/systemd/resolved.conf.d; do
    for f in "$(sysp "$d")"/*.conf; do [[ -f $f ]] && files+=("$f"); done
  done
  for f in "${files[@]}"; do
    [[ -r $f ]] || continue
    while IFS= read -r line; do
      line=$(trim "$line")
      [[ $line == "$key="* ]] && val=${line#"$key="}
    done <"$f"
  done
  printf '%s' "$val"
}

dns_detect() {
  local rc target head
  rc=$(sysp /etc/resolv.conf)
  DNS_RESOLV_TARGET='' DNS_MANAGER=unknown DNS_MANAGER_DETAIL='' DNS_UPSTREAM=() DNS_IMMUTABLE=0
  DNS_RESOLVCONF_FLAVOR='' DNS_DHCP_CLIENT='' DNS_NETPLAN_FILES=()

  if [[ -L $rc ]]; then
    DNS_RESOLV_KIND=symlink
    DNS_RESOLV_TARGET=$(readlink "$rc")
  elif [[ -f $rc ]]; then
    DNS_RESOLV_KIND='file'
  else
    DNS_RESOLV_KIND=missing
  fi

  DNS_RESOLVED_ACTIVE=0 DNS_NM_ACTIVE=0
  svc_is_active systemd-resolved && DNS_RESOLVED_ACTIVE=1
  svc_is_active NetworkManager && DNS_NM_ACTIVE=1

  # DHCP clients that rewrite resolv.conf on lease renewal
  if [[ -n $(proc_find dhclient) ]]; then
    DNS_DHCP_CLIENT=dhclient
  elif [[ -n $(proc_find dhcpcd) ]]; then
    DNS_DHCP_CLIENT=dhcpcd
  elif svc_is_active systemd-networkd; then
    DNS_DHCP_CLIENT=networkd
  fi

  local f
  for f in "$(sysp /etc/netplan)"/*.yaml; do
    [[ -f $f ]] && DNS_NETPLAN_FILES+=("${f#"${NEKO_SYSROOT:-}"}")
  done

  if [[ $DNS_RESOLV_KIND == symlink ]]; then
    target=$DNS_RESOLV_TARGET
    case $target in
      *systemd/resolve/stub-resolv.conf) DNS_MANAGER=systemd-resolved DNS_MANAGER_DETAIL=stub ;;
      *systemd/resolve/resolv.conf) DNS_MANAGER=systemd-resolved DNS_MANAGER_DETAIL=direct ;;
      *resolvconf/resolv.conf | *resolvconf/run/resolv.conf) DNS_MANAGER=resolvconf ;;
      *NetworkManager/*resolv.conf) DNS_MANAGER=NetworkManager ;;
      *) DNS_MANAGER=unknown DNS_MANAGER_DETAIL="symlink:$target" ;;
    esac
  elif [[ $DNS_RESOLV_KIND == file ]]; then
    head=$(head -n 8 "$rc" 2>/dev/null)
    case $head in
      *'Generated by Neko'*)
        # a Neko-written file is still rewritten by a running dhclient
        if [[ $DNS_DHCP_CLIENT == dhclient ]]; then DNS_MANAGER=dhclient; else DNS_MANAGER=static DNS_MANAGER_DETAIL=neko; fi
        ;;
      *'Generated by NetworkManager'*) DNS_MANAGER=NetworkManager ;;
      *'systemd-resolved'*) DNS_MANAGER=systemd-resolved DNS_MANAGER_DETAIL=copy ;;
      *'generated by resolvconf'* | *'Generated by resolvconf'*) DNS_MANAGER=resolvconf ;;
      *'dhclient-script'*) DNS_MANAGER=dhclient ;;
      *'dhcpcd'*) DNS_MANAGER=dhcpcd ;;
      *)
        case $DNS_DHCP_CLIENT in
          dhclient) DNS_MANAGER=dhclient DNS_MANAGER_DETAIL=running ;;
          dhcpcd) DNS_MANAGER=dhcpcd DNS_MANAGER_DETAIL=running ;;
          *) DNS_MANAGER=static ;;
        esac
        ;;
    esac
    if has_cmd lsattr && [[ -z ${NEKO_SYSROOT:-} ]]; then
      [[ $(lsattr -d "$rc" 2>/dev/null | awk '{print $1}') == *i* ]] && DNS_IMMUTABLE=1
    fi
  fi
  # NetworkManager can delegate to systemd-resolved; the stub link wins in that case
  [[ $DNS_MANAGER == unknown && $DNS_NM_ACTIVE == 1 ]] && DNS_MANAGER=NetworkManager

  if [[ $DNS_MANAGER == resolvconf ]]; then
    if has_cmd resolvconf && resolvconf --version 2>/dev/null | grep -qi openresolv; then
      DNS_RESOLVCONF_FLAVOR=openresolv
    else
      DNS_RESOLVCONF_FLAVOR=debian
    fi
  fi

  dns_parse_resolv "$rc"
  if [[ $DNS_MANAGER == systemd-resolved ]]; then
    local saved=("${DNS_NAMESERVERS[@]}") s=$DNS_SEARCH o=$DNS_OPTIONS
    if dns_parse_resolv "$(sysp /run/systemd/resolve/resolv.conf)"; then
      DNS_UPSTREAM=("${DNS_NAMESERVERS[@]}")
    fi
    DNS_NAMESERVERS=("${saved[@]}") DNS_SEARCH=$s DNS_OPTIONS=$o
  else
    DNS_UPSTREAM=("${DNS_NAMESERVERS[@]}")
  fi

  dns_detect_encryption
}

dns_detect_encryption() {
  DNS_DOT=no DNS_DOH=none
  if [[ $DNS_MANAGER == systemd-resolved || $DNS_RESOLVED_ACTIVE == 1 ]]; then
    local v
    v=$(dns_resolved_conf_value DNSOverTLS)
    case ${v,,} in
      yes | true | 1 | on) DNS_DOT=yes ;;
      opportunistic) DNS_DOT=opportunistic ;;
      *) DNS_DOT=no ;;
    esac
  fi
  local p
  for p in cloudflared dnscrypt-proxy dnsproxy AdGuardHome; do
    if [[ -n $(proc_find "$p") ]]; then
      DNS_DOH=$p
      break
    fi
  done
}

dns_manager_label() {
  case $DNS_MANAGER in
    systemd-resolved)
      case $DNS_MANAGER_DETAIL in
        stub) echo 'systemd-resolved（本地 stub 127.0.0.53）' ;;
        direct) echo 'systemd-resolved（直接上游模式）' ;;
        *) echo 'systemd-resolved' ;;
      esac
      ;;
    resolvconf) echo "resolvconf（${DNS_RESOLVCONF_FLAVOR:-debian}）" ;;
    NetworkManager) echo 'NetworkManager' ;;
    dhclient) echo 'DHCP 客户端 dhclient（续租时会改写 resolv.conf）' ;;
    dhcpcd) echo 'DHCP 客户端 dhcpcd（续租时会改写 resolv.conf）' ;;
    static)
      if [[ $DNS_MANAGER_DETAIL == neko ]]; then echo '静态文件（由 Neko 生成）'; else echo '静态文件（无管理程序）'; fi
      ;;
    *) echo "未知（${DNS_MANAGER_DETAIL:-无法识别}）" ;;
  esac
}

dns_dot_label() {
  case $DNS_DOT in
    yes) ui_status good '已启用（严格模式）' ;;
    opportunistic) ui_status warn '机会模式（可降级为明文）' ;;
    *) echo '未启用' ;;
  esac
}

# Short DNS summary for the main menu.
dns_summary() {
  local list=("${DNS_UPSTREAM[@]}")
  ((${#list[@]})) || list=("${DNS_NAMESERVERS[@]}")
  if ((${#list[@]} == 0)); then
    echo '未配置'
  elif ((${#list[@]} == 1)); then
    echo "${list[0]}"
  else
    echo "${list[0]}, ${list[1]}"
  fi
}

dns_report() {
  ui_section "DNS 配置"
  ui_kv "管理方式" "$(dns_manager_label)"
  case $DNS_RESOLV_KIND in
    symlink) ui_kv "resolv.conf" "符号链接 → ${DNS_RESOLV_TARGET}" ;;
    file) ui_kv "resolv.conf" "普通文件$( ((DNS_IMMUTABLE)) && echo '（已设置 immutable 属性）')" ;;
    *) ui_kv "resolv.conf" "$(ui_status bad 不存在)" ;;
  esac
  ui_kv "resolv.conf 内" "${DNS_NAMESERVERS[*]:-无 nameserver}"
  [[ $DNS_MANAGER == systemd-resolved ]] && ui_kv "上游 DNS" "${DNS_UPSTREAM[*]:-未知}"
  ui_kv "DoT" "$(dns_dot_label)"
  [[ $DNS_DOH != none ]] && ui_kv "DoH 转发器" "检测到 ${DNS_DOH} 正在运行"
  ui_kv "DHCP 客户端" "${DNS_DHCP_CLIENT:-未检测到}"
  ((${#DNS_NETPLAN_FILES[@]})) && ui_kv "netplan" "${DNS_NETPLAN_FILES[*]}"
  ui_kv "NetworkManager" "$( ((DNS_NM_ACTIVE)) && echo 运行中 || echo 未运行)"
}
