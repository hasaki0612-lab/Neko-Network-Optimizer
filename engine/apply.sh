# shellcheck shell=bash
# Neko - change application engine.
#
# All sysctl tuning lives in ONE managed file that is regenerated from a
# key/value map on every change, so repeated runs never append duplicates.
# The file name sorts after Debian's 99-sysctl.conf -> /etc/sysctl.conf link,
# so Neko's values win at boot; any later file that overrides them is reported.

[[ -n ${_NEKO_APPLY_LOADED:-} ]] && return 0
_NEKO_APPLY_LOADED=1

NEKO_SYSCTL_FILE=/etc/sysctl.d/99-zz-neko.conf
NEKO_MODULES_FILE=/etc/modules-load.d/neko.conf
SYSCTL_DIRS=(/etc/sysctl.d /run/sysctl.d /usr/local/lib/sysctl.d /usr/lib/sysctl.d /lib/sysctl.d)

# profile_args <name>: key=value lines of data/profiles/<name>.conf
profile_args() {
  grep -Ev '^[[:space:]]*(#|$)' "$NEKO_HOME/data/profiles/$1.conf" 2>/dev/null | tr -d ' 	'
}

# Preconditions shared by every modifying action.
apply_preflight() { # apply_preflight <action>
  require_root "$1" || return 1
  sys_allow_modify || return 1
  backup_init || return 1
}

# managed_sysctl_load <assoc-array-name>
managed_sysctl_load() {
  local -n _m=$1
  local f k v line
  f=$(sysp "$NEKO_SYSCTL_FILE")
  [[ -r $f ]] || return 0
  while IFS= read -r line; do
    line=$(trim "$line")
    [[ -z $line || $line == \#* || $line == \;* ]] && continue
    k=$(trim "${line%%=*}")
    v=$(trim "${line#*=}")
    validate_sysctl_key "$k" && _m[$k]=$v
  done <"$f"
}

managed_sysctl_write() { # managed_sysctl_write <assoc-array-name>
  local -n _w=$1
  local f tmp k
  f=$(sysp "$NEKO_SYSCTL_FILE")
  mkdir -p "$(dirname "$f")" || return 1
  if ((${#_w[@]} == 0)); then
    rm -f "$f"
    return 0
  fi
  tmp=$(mktemp "${f}.XXXXXX") || return 1
  {
    echo "# Generated by Neko VPS Network Optimizer ${NEKO_VERSION:-}"
    echo "# Managed file: edit through 'neko' so changes stay backed up."
    echo "# Rollback: neko -> 9. 配置备份与回滚"
    for k in $(printf '%s\n' "${!_w[@]}" | sort); do
      printf '%s = %s\n' "$k" "${_w[$k]}"
    done
  } >"$tmp"
  chmod 644 "$tmp" && mv -f "$tmp" "$f"
}

# Lists other sysctl files that set <key> to a different value.
# Output: "path<TAB>value<TAB>after|before" (after = applied later at boot, wins over Neko).
sysctl_conflicts() { # sysctl_conflicts <key> <value>
  local key=$1 want=$2 d f base line k v ours
  local -a _parts=()
  ours=$(basename "$NEKO_SYSCTL_FILE")
  local -A seen=()
  local files=()
  for d in "${SYSCTL_DIRS[@]}"; do
    for f in "$(sysp "$d")"/*.conf; do
      [[ -f $f ]] || continue
      base=${f##*/}
      [[ -n ${seen[$base]+x} ]] && continue # /etc overrides same-named files in /usr/lib
      seen[$base]=1
      files+=("$f")
    done
  done
  [[ -f $(sysp /etc/sysctl.conf) && -z ${seen[99-sysctl.conf]+x} ]] && files+=("$(sysp /etc/sysctl.conf)")
  for f in "${files[@]}"; do
    base=${f##*/}
    [[ $base == "$ours" ]] && continue
    while IFS= read -r line; do
      line=$(trim "$line")
      [[ -z $line || $line == \#* || $line == \;* ]] && continue
      line=${line#-}
      k=$(trim "${line%%=*}")
      k=${k//\//.}
      [[ $k == "$key" ]] || continue
      v=$(trim "${line#*=}")
      read -ra _parts <<<"$v"
      v="${_parts[*]}"
      [[ $v == "$want" ]] && continue
      if [[ $base > "$ours" ]]; then
        printf '%s\t%s\tafter\n' "${f#"${NEKO_SYSROOT:-}"}" "$v"
      else
        printf '%s\t%s\tbefore\n' "${f#"${NEKO_SYSROOT:-}"}" "$v"
      fi
    done <"$f"
  done
}

# apply_sysctl <label> <summary> key=value...
#   Optional env: APPLY_MODULES="tcp_bbr ..."  -> persisted in modules-load.d
#                 APPLY_ASSUME_YES=1            -> skip the confirmation (caller asked already)
# Returns 0 when applied (or nothing to do), 1 when cancelled/failed.
apply_sysctl() {
  local label=$1 summary=$2
  shift 2
  apply_preflight "修改内核网络参数" || return 1

  local -A want=() cur=() managed=()
  local -a keys=() skipped=() failed=()
  local kv k v
  for kv in "$@"; do
    k=${kv%%=*} v=${kv#*=}
    if ! validate_sysctl_key "$k" || ! validate_sysctl_value "$v"; then
      ui_err "非法参数：${kv}"
      return 1
    fi
    if ! sysctl_exists "$k"; then
      skipped+=("${k}（当前内核不存在此参数）")
      continue
    fi
    if ! sysctl_writable "$k"; then
      if sys_is_container; then
        skipped+=("${k}（容器环境中只读，由宿主机控制）")
      else
        skipped+=("${k}（只读）")
      fi
      continue
    fi
    want[$k]=$v
    cur[$k]=$(sysctl_get "$k")
    keys+=("$k")
  done

  ui_section "参数变更预览"
  local changes=0
  printf '  %s %s %s\n' "$(ui_pad 参数 38)" "$(ui_pad 当前值 22)" "目标值"
  for k in "${keys[@]}"; do
    local mark=''
    if [[ ${cur[$k]} != "${want[$k]}" ]]; then
      ((changes++))
      mark=' *'
    fi
    printf '  %s %s %s%s\n' "$(ui_pad "$k" 38)" "$(ui_pad "${cur[$k]}" 22)" "${want[$k]}" "$mark"
  done
  for kv in "${skipped[@]}"; do ui_warn "跳过：${kv}"; done

  managed_sysctl_load managed
  local file_changes=0
  for k in "${keys[@]}"; do
    [[ ${managed[$k]:-} != "${want[$k]}" ]] && ((file_changes++))
  done

  if ((${#keys[@]} == 0)); then
    ui_err "没有可应用的参数。"
    return 1
  fi
  if ((changes == 0 && file_changes == 0)); then
    ui_ok "当前配置已是目标值，且已持久化，无需修改。"
    return 0
  fi

  local has_after=0 f when
  for k in "${keys[@]}"; do
    while IFS=$'\t' read -r f v when; do
      [[ -n $f ]] || continue
      if [[ $when == after ]]; then
        ui_warn "${f} 将 ${k} 设为 ${v}，且在 Neko 之后加载，重启后会覆盖 Neko 的设置。"
        has_after=1
      else
        ui_note "提示：${f} 将 ${k} 设为 ${v}（会被 Neko 的配置覆盖）。"
      fi
    done < <(sysctl_conflicts "$k" "${want[$k]}")
  done
  ((has_after)) && ui_note "如需保持 Neko 设置，请手动检查上述文件。"

  ui_note "配置文件：${NEKO_SYSCTL_FILE}（修改前自动备份，可在菜单 9 中回滚）"
  if [[ ${APPLY_ASSUME_YES:-0} != 1 ]]; then
    ui_confirm "确认应用以上 ${changes} 项运行时修改并持久化吗？" n || {
      ui_info "已取消，未做任何修改。"
      return 1
    }
  fi

  neko_lock || return 1
  backup_begin "$label" "$summary" || { neko_unlock; return 1; }
  backup_add_file "$NEKO_SYSCTL_FILE" || { backup_abort_and_restore; neko_unlock; return 1; }
  backup_record_sysctl "${keys[@]}"
  if [[ -n ${APPLY_MODULES:-} ]]; then
    backup_add_file "$NEKO_MODULES_FILE" || { backup_abort_and_restore; neko_unlock; return 1; }
    # shellcheck disable=SC2086 # space separated module list
    apply_modules_file $APPLY_MODULES || failed+=("$NEKO_MODULES_FILE")
  fi

  for k in "${keys[@]}"; do managed[$k]=${want[$k]}; done
  if ! managed_sysctl_write managed; then
    ui_err "写入 ${NEKO_SYSCTL_FILE} 失败。"
    backup_abort_and_restore
    neko_unlock
    return 1
  fi

  for k in "${keys[@]}"; do
    [[ ${cur[$k]} == "${want[$k]}" ]] && continue
    if ! sysctl_set_runtime "$k" "${want[$k]}" || [[ $(sysctl_get "$k") != "${want[$k]}" ]]; then
      failed+=("$k")
    fi
  done
  local tx=$BK_TX_ID
  backup_commit
  neko_unlock

  if ((${#failed[@]})); then
    ui_err "以下参数应用失败：${failed[*]}"
    log_error "apply_sysctl ${label} failed keys: ${failed[*]}"
    if ui_confirm "是否回滚本次变更？" y; then
      backup_restore_to "$tx" auto
    fi
    return 1
  fi
  ui_ok "已应用并持久化（变更编号 ${tx}）。"
  log_info "apply_sysctl ${label} ok tx=${tx}: $*"
  return 0
}

apply_modules_file() { # apply_modules_file <module>...
  local f m tmp
  f=$(sysp "$NEKO_MODULES_FILE")
  mkdir -p "$(dirname "$f")" || return 1
  tmp=$(mktemp "${f}.XXXXXX") || return 1
  {
    echo "# Generated by Neko: kernel modules required by Neko's sysctl settings"
    for m in "$@"; do echo "$m"; done
  } >"$tmp"
  chmod 644 "$tmp" && mv -f "$tmp" "$f"
}

# ------------------------------------------------------------ auto guard ---
# High-risk changes (DNS) arm a guard that rolls back automatically unless the
# user confirms in time - even if the SSH session dies in between.

guard_dir() { printf '%s/guard' "$NEKO_STATE_DIR"; }

guard_arm() { # guard_arm <tx> <seconds>
  local tx=$1 t=$2 d bin
  d=$(guard_dir)
  (umask 077 && mkdir -p "$d") || return 1
  : >"$d/$tx.armed"
  bin=${NEKO_BIN:-$NEKO_HOME/neko.sh}
  if [[ -z ${NEKO_SYSROOT:-} ]] && svc_has_systemd && has_cmd systemd-run; then
    if systemd-run --quiet --unit="neko-guard-$tx" --on-active="${t}s" \
      --timer-property=AccuracySec=1s "$bin" --guard-rollback "$tx" >/dev/null 2>&1; then
      echo systemd >"$d/$tx.kind"
      return 0
    fi
  fi
  if has_cmd setsid; then
    setsid nohup bash -c 'sleep "$1"; exec "$2" --guard-rollback "$3"' _ "$t" "$bin" "$tx" >/dev/null 2>&1 &
  else
    nohup bash -c 'sleep "$1"; exec "$2" --guard-rollback "$3"' _ "$t" "$bin" "$tx" >/dev/null 2>&1 &
  fi
  echo "$!" >"$d/$tx.pid"
  echo process >"$d/$tx.kind"
}

guard_disarm() { # guard_disarm <tx>
  local tx=$1 d pid
  d=$(guard_dir)
  rm -f "$d/$tx.armed"
  if [[ $(cat "$d/$tx.kind" 2>/dev/null) == systemd ]]; then
    systemctl stop "neko-guard-$tx.timer" >/dev/null 2>&1 || true
  elif [[ -f $d/$tx.pid ]]; then
    pid=$(<"$d/$tx.pid")
    [[ $pid =~ ^[0-9]+$ ]] && kill "$pid" 2>/dev/null
  fi
  rm -f "$d/$tx.kind" "$d/$tx.pid"
}

# Entry point for "neko --guard-rollback <tx>" (runs unattended).
guard_fire() {
  local tx=$1 d
  d=$(guard_dir)
  [[ $tx =~ ^[0-9]{5}-[0-9]{8}-[0-9]{6}$ ]] || return 1
  [[ -f $d/$tx.armed ]] || return 0 # confirmed or already handled
  rm -f "$d/$tx.armed" "$d/$tx.kind" "$d/$tx.pid"
  log_warn "guard timeout: rolling back ${tx}"
  backup_restore_to "$tx" auto
}

# guard_confirm <tx> <seconds> <verify-function>
# Arms the guard, asks the user to keep the change, rolls back on "no" or timeout.
guard_confirm() {
  local tx=$1 t=$2 ans
  guard_arm "$tx" "$t" || ui_warn "无法启动自动回滚守护，将仅依赖本次会话内的确认。"
  ui_warn "已启用自动回滚保护：${t} 秒内未确认将自动恢复原配置。"
  printf '请检查网络与 DNS 是否正常。是否保留本次修改？[y/N]（%s 秒后自动回滚）：' "$t"
  if IFS= read -r -t "$t" ans; then
    ans=$(trim "${ans,,}")
  else
    echo
    ans=timeout
  fi
  guard_disarm "$tx"
  case $ans in
    y | yes | 是)
      ui_ok "已确认保留本次修改。"
      return 0
      ;;
    timeout) ui_warn "确认超时，正在自动回滚..." ;;
    *) ui_info "未确认保留，正在回滚..." ;;
  esac
  backup_restore_to "$tx" auto
  return 1
}
